/**
 * GeoRank Pro - Agency Masterclass & Training Guide Modal
 * Path: /src/components/training/MasterclassModal.tsx
 *
 * Implements:
 * - High-impact Agency Training Guide with structured lesson syllabus
 * - Illustrated Video Placeholder with "Video Module in Production • Written SOP Guide Below" indicator
 * - Core Implementation Takeaways & Actionable Steps
 * - Downloadable SOP Checklist (Generates and downloads a clean agency playbook .md file)
 */

import React, { useState } from 'react';
import {
  BookOpen,
  X,
  Play,
  CheckCircle2,
  Clock,
  Download,
  FileText,
  Sparkles,
  Check,
  AlertCircle,
  Award,
} from 'lucide-react';
import type { TrainingModule } from '../views/TrainingView.tsx';

export interface MasterclassModalProps {
  module: TrainingModule | null;
  onClose: () => void;
  onToggleComplete: (moduleId: string) => void;
}

export const MasterclassModal: React.FC<MasterclassModalProps> = ({
  module,
  onClose,
  onToggleComplete,
}) => {
  const [downloadSuccess, setDownloadSuccess] = useState(false);

  if (!module) return null;

  const handleDownloadSOP = () => {
    const markdownContent = `# GeoRank Pro Agency SOP Playbook
## Module: ${module.title}
**Category**: ${module.category} | **Duration**: ${module.duration} | **Level**: ${module.level}

---

### Core Implementation Principles:
${module.takeaways.map((t, idx) => `${idx + 1}. ${t}`).join('\n')}

---

### Standard Operating Procedure (SOP) Checklist:
${module.checklist.map((c) => `- [ ] ${c}`).join('\n')}

---

*Generated by GeoRank Pro Academy. Use this SOP to standardize local map client prospecting and fulfillment.*
`;

    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `GeoRank_SOP_${module.id}_${module.title.toLowerCase().replace(/[^a-z0-9]+/g, '_')}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    setDownloadSuccess(true);
    setTimeout(() => setDownloadSuccess(false), 3000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/60 backdrop-blur-xs animate-in fade-in duration-150">
      <div className="bg-white rounded-3xl border border-slate-200/90 shadow-2xl w-full max-w-2xl overflow-hidden flex flex-col max-h-[90vh]">
        {/* Modal Header */}
        <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between bg-slate-50/70">
          <div className="flex items-center space-x-2.5">
            <div className="p-2 bg-emerald-50 text-emerald-700 rounded-xl border border-emerald-100">
              <BookOpen className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-bold text-slate-900 text-sm tracking-tight">
                {module.title}
              </h3>
              <span className="text-[11px] text-slate-500 font-medium">
                {module.category} • {module.duration} • Level: {module.level}
              </span>
            </div>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-slate-600 p-1.5 rounded-lg hover:bg-slate-200/60 transition cursor-pointer"
            aria-label="Close training modal"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-6 overflow-y-auto space-y-5 text-xs">
          {/* Enhanced Media Container with Status Indicator */}
          <div className="w-full bg-gradient-to-br from-slate-950 via-slate-900 to-slate-950 rounded-2xl p-6 text-white border border-slate-800 shadow-inner flex flex-col items-center justify-center text-center relative overflow-hidden group">
            {/* Background subtle radial glow */}
            <div className="absolute inset-0 bg-radial from-emerald-500/10 via-transparent to-transparent opacity-50" />

            <div className="relative z-10 space-y-3 max-w-md">
              <div className="w-12 h-12 rounded-2xl bg-emerald-500/20 border border-emerald-500/40 text-emerald-400 flex items-center justify-center mx-auto shadow-lg backdrop-blur-xs">
                <Play className="w-5 h-5 fill-current ml-0.5" />
              </div>

              <div>
                <div className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-[10px] font-bold bg-amber-500/20 text-amber-300 border border-amber-500/30 mb-1.5">
                  <span className="w-1.5 h-1.5 rounded-full bg-amber-400 animate-pulse" />
                  <span>HD Video Module In Production • Complete Written Guide Below</span>
                </div>
                <h4 className="font-bold text-sm text-slate-100">
                  {module.title}
                </h4>
                <p className="text-[11px] text-slate-400 mt-1">
                  Full step-by-step SOP curriculum and actionable implementation breakdown provided below.
                </p>
              </div>
            </div>
          </div>

          {/* Action SOP Download Strip */}
          <div className="p-3.5 bg-emerald-50/70 border border-emerald-200/90 rounded-2xl flex items-center justify-between gap-3">
            <div className="flex items-center space-x-2 text-emerald-950">
              <FileText className="w-4 h-4 text-emerald-600 shrink-0" />
              <div>
                <span className="font-bold block text-xs">Download Agency SOP Playbook</span>
                <span className="text-[11px] text-emerald-700">
                  Includes step-by-step checklists, email templates, and outreach scripts
                </span>
              </div>
            </div>

            <button
              onClick={handleDownloadSOP}
              className="px-3.5 py-1.5 bg-emerald-600 hover:bg-emerald-500 text-white rounded-xl text-xs font-bold transition flex items-center space-x-1.5 shrink-0 shadow-2xs cursor-pointer"
            >
              {downloadSuccess ? (
                <>
                  <Check className="w-3.5 h-3.5" />
                  <span>Downloaded!</span>
                </>
              ) : (
                <>
                  <Download className="w-3.5 h-3.5" />
                  <span>Download .MD</span>
                </>
              )}
            </button>
          </div>

          {/* Core Implementation Takeaways */}
          <div className="space-y-2">
            <div className="font-bold text-slate-900 uppercase tracking-wider text-[11px] flex items-center space-x-1.5">
              <Sparkles className="w-3.5 h-3.5 text-amber-500" />
              <span>Core Implementation Takeaways:</span>
            </div>
            <div className="space-y-2">
              {module.takeaways.map((point, i) => (
                <div
                  key={i}
                  className="p-3 bg-slate-50 border border-slate-200/80 rounded-xl text-slate-800 font-medium leading-relaxed"
                >
                  {point}
                </div>
              ))}
            </div>
          </div>

          {/* Step-by-Step Curriculum */}
          <div className="space-y-2">
            <div className="font-bold text-slate-900 uppercase tracking-wider text-[11px] flex items-center space-x-1.5">
              <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
              <span>Actionable Step-by-Step Curriculum:</span>
            </div>
            <div className="space-y-2">
              {module.checklist.map((step, i) => (
                <div
                  key={i}
                  className="flex items-start space-x-2.5 p-2.5 bg-white border border-slate-100 rounded-xl"
                >
                  <span className="w-5 h-5 rounded-full bg-emerald-100 text-emerald-800 text-[10px] font-bold flex items-center justify-center shrink-0 mt-0.5">
                    {i + 1}
                  </span>
                  <span className="text-slate-700 leading-relaxed">{step}</span>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Modal Footer */}
        <div className="px-6 py-3.5 border-t border-slate-100 bg-slate-50/70 flex items-center justify-between text-xs">
          <button
            onClick={() => {
              onToggleComplete(module.id);
              onClose();
            }}
            className="px-4 py-2 bg-emerald-600 hover:bg-emerald-500 text-white rounded-xl font-bold transition flex items-center space-x-1.5 cursor-pointer shadow-2xs"
          >
            <Check className="w-3.5 h-3.5 stroke-[3]" />
            <span>{module.completed ? 'Keep Completed' : 'Mark Lesson Complete'}</span>
          </button>
          <button
            onClick={onClose}
            className="px-4 py-2 bg-white border border-slate-200 text-slate-700 rounded-xl font-semibold hover:bg-slate-50 transition cursor-pointer"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
